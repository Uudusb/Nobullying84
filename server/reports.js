function asciiPdf(lines) {
  const safe = lines.map((line) => String(line).replace(/[^\x20-\x7E]/g, "?")).slice(0, 40);
  const commands = ["BT", "/F1 11 Tf", "48 760 Td", "14 TL"];
  safe.forEach((line, i) => {
    const escaped = line.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
    commands.push(i === 0 ? `(${escaped}) Tj` : `T* (${escaped}) Tj`);
  });
  commands.push("ET");
  const stream = commands.join("\n");
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Count 1 /Kids [3 0 R] >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
    `<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
  ];
  let body = "%PDF-1.4\n";
  const offsets = [0];
  objects.forEach((obj, i) => {
    offsets.push(Buffer.byteLength(body));
    body += `${i + 1} 0 obj\n${obj}\nendobj\n`;
  });
  const xref = Buffer.byteLength(body);
  body += `xref\n0 ${objects.length + 1}\n`;
  body += "0000000000 65535 f \n";
  for (let i = 1; i < offsets.length; i++) body += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
  body += `trailer << /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  return Buffer.from(body);
}

export async function htmlToPdf(html, fallbackLines) {
  const chrome = "/usr/bin/google-chrome";
  const dir = await mkdtemp(join(tmpdir(), "si-pdf-"));
  try {
    const htmlPath = join(dir, "report.html");
    const pdfPath = join(dir, "report.pdf");
    await writeFile(htmlPath, html);
    await new Promise((resolve, reject) => {
      const child = spawn(chrome, [
        "--headless=new",
        "--disable-gpu",
        "--no-sandbox",
        "--disable-dev-shm-usage",
        `--user-data-dir=${join(dir, "profile")}`,
        `--print-to-pdf=${pdfPath}`,
        "--no-pdf-header-footer",
        `file://${htmlPath}`,
      ], { stdio: "ignore" });
      const timer = setTimeout(() => {
        child.kill();
        reject(new Error("pdf timeout"));
      }, 25000);
      child.on("error", (err) => {
        clearTimeout(timer);
        reject(err);
      });
      child.on("exit", (code) => {
        clearTimeout(timer);
        if (code === 0) resolve();
        else reject(new Error(`pdf exit ${code}`));
      });
    });
    return await readFile(pdfPath);
  } catch {
    return asciiPdf(fallbackLines);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

export function cadenceKey(iso, cadence) {
  const day = iso.slice(0, 10);
  if (cadence === "monthly") return day.slice(0, 7);
  if (cadence === "weekly") {
    const date = new Date(`${day}T00:00:00Z`);
    const onejan = new Date(Date.UTC(date.getUTCFullYear(), 0, 1));
    const week = Math.ceil((((date - onejan) / 86400000) + onejan.getUTCDay() + 1) / 7);
    return `${date.getUTCFullYear()}-W${String(week).padStart(2, "0")}`;
  }
  return day;
}
